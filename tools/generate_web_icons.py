#!/usr/bin/env python3
"""Embed exact launcher RGBA icons as PNG using only stdlib; retain upstream credits."""
from pathlib import Path
import re,struct,zlib,base64,json
ROOT=Path(__file__).resolve().parents[1]
def generated():
    source=(ROOT/'client/launcher/instance_icons.hpp').read_text()
    values=[int(v,16) for v in re.findall(r'0x([a-f0-9]+)u',source)]
    assert len(values)==32*72*72
    def chunk(t,b):return struct.pack('>I',len(b))+t+b+struct.pack('>I',zlib.crc32(t+b))
    images=[]
    for i in range(32):
        rgba=b''.join(struct.pack('<I',p) for p in values[i*72*72:(i+1)*72*72])
        scan=b''.join(b'\0'+rgba[y*288:(y+1)*288] for y in range(72))
        png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',72,72,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(scan,9))+chunk(b'IEND',b'')
        images.append(base64.b64encode(png).decode())
    return '// Generated by tools/generate_web_icons.py from exact launcher pixels.\n// Prism/MultiMC CC-BY-SA-4.0; original Amethyst/Compass CC0-1.0; see assets/launcher-icons/attribution.json. Icon0: ProsperoCraft.\nfinal class ProsperoWebIcons {static final String[] PNG={\n'+',\n'.join(json.dumps(s) for s in images)+'\n};}\n'
if __name__=='__main__':(ROOT/'client/launcher/java/ProsperoWebIcons.java').write_text(generated())
